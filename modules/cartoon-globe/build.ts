import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

await build({ configFile: fileURLToPath(new URL('./vite.config.ts', import.meta.url)) });
const script = await readFile(new URL('./.build/globe.js', import.meta.url), 'utf8');
const template = await readFile(new URL('./src/template.html', import.meta.url), 'utf8');
const font = await readFile(new URL('../../node_modules/@expo-google-fonts/nunito/600SemiBold/Nunito_600SemiBold.ttf', import.meta.url));
const fontFace = `@font-face{font-family:Nunito;src:url(data:font/ttf;base64,${font.toString('base64')}) format('truetype');font-weight:600;font-display:swap}`;
const html = template
  .replace('/* TRAVI_FONT_FACE */', () => fontFace)
  .replace('/* GLOBE_SCRIPT */', () => script.replace(/<\/script/gi, '<\\/script'));
await mkdir(new URL('../../src/generated/', import.meta.url), { recursive: true });
await writeFile(new URL('../../src/generated/cartoon-globe-html.ts', import.meta.url),
  '// Generated by bun run globe:build. Do not edit.\nexport const CARTOON_GLOBE_HTML = ' + JSON.stringify(html) + ';\n');
console.log(`Bundled cartoon globe: ${(html.length / 1024).toFixed(0)} KB; no localhost server required.`);
